-- ============================================================================
-- HCQHA Live Scoring — database CATCH-UP script
-- ============================================================================
-- Run in Supabase: SQL Editor -> New query -> paste ALL of this -> Run.
--
-- Applies every database update this version of the website needs, in order,
-- and skips anything the database already has. Safe to run as often as you
-- like: run it after every website update, or on a brand-new database to set
-- it up from nothing.
--
-- How it decides what to skip: a small table, schema_versions, records each
-- file the moment it is applied. The first time this runs on an existing
-- database that table is empty, so each file is also checked against the
-- database itself (does the table / column it adds exist?) and recorded as
-- "already in place" without being re-run.
--
-- If anything fails, NOTHING is kept (the whole run is one transaction) and
-- the error names the file that failed. The result shown at the end lists
-- every update with what happened to it this run.
--
-- Generated by scripts/build-catch-up-sql.mjs from the numbered files in
-- supabase/ — edit those, not this.
-- ============================================================================

create table if not exists schema_versions (
  file        text primary key,            -- e.g. 'schema-v63-judge-cards.sql'
  version     integer not null,
  applied_at  timestamptz not null default now(),
  how         text not null,               -- 'applied by catch-up' | 'already in place'
  last_run_at timestamptz,
  last_result text
);
alter table schema_versions enable row level security;
revoke all on schema_versions from anon;
revoke all on schema_versions from authenticated;

create or replace function catch_up_has_table(t text) returns boolean
language sql stable as $fn$ select to_regclass('public.' || t) is not null $fn$;

create or replace function catch_up_has_column(t text, c text) returns boolean
language sql stable as $fn$
  select exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = t and column_name = c
  )
$fn$;

-- Runs one file unless it has been recorded, or the probe says it's in place.
create or replace function catch_up_apply(p_file text, p_version integer, p_probe text, p_sql text)
returns text language plpgsql as $fn$
declare
  present boolean := false;
  result  text;
begin
  if exists (select 1 from schema_versions where file = p_file) then
    result := 'skipped — recorded earlier';
  else
    if p_probe is not null then
      execute 'select ' || p_probe into present;
    end if;
    if present then
      result := 'skipped — already in place';
      insert into schema_versions (file, version, how) values (p_file, p_version, 'already in place');
    else
      begin
        execute p_sql;
      exception when others then
        raise exception 'Update % failed: %', p_file, sqlerrm using errcode = sqlstate, hint = 'Nothing was changed. Fix the cause and run the catch-up script again.';
      end;
      result := 'applied';
      insert into schema_versions (file, version, how) values (p_file, p_version, 'applied by catch-up');
    end if;
  end if;
  update schema_versions set last_run_at = now(), last_result = result where file = p_file;
  return result;
end
$fn$;

